import { chromium } from 'playwright';
const base = process.argv[2];
const rec = (n, ok, d = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${d ? ' — ' + d : ''}`);
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
const page = await ctx.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
const txt = s => page.locator(s).innerText(), wait = ms => page.waitForTimeout(ms);
await page.goto(base + '/index.html'); await page.waitForSelector('#clock'); await wait(800);
await page.locator('#eden').tap(); await wait(500);
const islandClock = await txt('#clock');
rec('Eden dialog explains the world and offers entry', (await txt('#edenDialog')).includes('No outcome is scripted') && await page.locator('#enterEden').isVisible());
await page.locator('#enterEden').tap(); await wait(500);
rec('entering Eden shows guided phase', /Eden · guided/.test(await txt('#hint')), await txt('#hint'));
rec('Eden button becomes Leave Eden; powers disabled', (await txt('#eden')) === 'Leave Eden' && await page.locator('#give').isDisabled() && await page.locator('#bridge').isDisabled() && await page.locator('#reveal').isDisabled());
await page.locator('#world').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'shots/eden-01-start.png' });
await page.locator('#speed').tap(); await wait(15000);
await page.locator('details summary').tap(); await wait(300);
const knowledge = await txt('#knowledge'); const decision = await txt('#decision');
rec('inspector shows sex, age, curiosity, serpent and guidance', /(Female|Male) · age \d+/.test(knowledge) && /Curiosity \d+%/.test(knowledge) && /led by the Creator/.test(knowledge), knowledge.replace(/\n/g, ' | '));
await page.screenshot({ path: 'shots/eden-02-running.png', fullPage: true });
let guidedSeen = false;
for (let i = 0; i < 24 && !guidedSeen; i++) { if (/not its own decision/.test(await txt('#decision'))) guidedSeen = true; else { await page.locator('#next').tap(); await wait(80); } }
rec('inspector can show a choice the Creator overrode', guidedSeen, guidedSeen ? (await txt('#decision')).split('\n')[1] : 'none visible in this moment');
await page.locator('#save').tap(); await wait(200);
rec('Save is blocked inside Eden', /Return to your island first/.test(await txt('#toast')));
await page.locator('#eden').tap(); await wait(400);
rec('Leave Eden returns to the island', (await txt('#eden')) === 'Eden' && !/Eden/.test(await txt('#hint')) && (await txt('#clock')) === islandClock, `${await txt('#clock')} vs ${islandClock}`);
rec('no page errors', errors.length === 0, errors.join(' | ') || 'none');
await b.close();
